const fs = require('fs');
const path = require('path');

const dir = path.join(__dirname, 'frontend', 'src', 'pages');
const files = fs.readdirSync(dir).filter(f => f.endsWith('.tsx'));

files.forEach(file => {
  let content = fs.readFileSync(path.join(dir, file), 'utf8');

  // Find all function declarations: function foo(a) {
  let funcs = [...content.matchAll(/function\s+([a-zA-Z0-9_]+)\s*\(/g)];
  
  if (funcs.length > 0) {
    let bindings = '\n        // Bindings generated by script\n';
    let added = new Set();
    funcs.forEach(f => {
      let name = f[1];
      if (!added.has(name) && name !== 'useEffect' && name !== 'useState') {
        bindings += `        if (typeof window !== "undefined") { (window as any).${name} = ${name}; }\n`;
        added.add(name);
      }
    });

    // inject bindings right before the end of the useEffect
    // The useEffect typically ends with:
    //     ` }} />
    //   );
    // }
    // Or we can just put it before the closing bracket of useEffect.
    // Let's find the end of useEffect. Usually it's right before the `return` statement.
    
    if (content.includes('// Bindings generated by script')) {
        console.log(`Already bound ${file}`);
        return;
    }
    
    // Most files have `return (` or `return <div`
    // We can inject it right before `return (` if it's a giant useEffect
    let parts = content.split('return (');
    if (parts.length >= 2) {
        let lastPart = parts.pop();
        let frontPart = parts.join('return (');
        content = frontPart + bindings + '\n    return (' + lastPart;
        fs.writeFileSync(path.join(dir, file), content);
        console.log(`Fixed ${file}`);
    } else {
        // some files like Sons.tsx might not have `return (` but instead return <div ... dangerouslySetInnerHTML={{ __html: `...` }} />
        let parts2 = content.split('return <div');
        if (parts2.length >= 2) {
            let lastPart = parts2.pop();
            let frontPart = parts2.join('return <div');
            content = frontPart + bindings + '\n    return <div' + lastPart;
            fs.writeFileSync(path.join(dir, file), content);
            console.log(`Fixed ${file} (with return <div)`);
        } else {
             console.log(`Could not find where to inject bindings in ${file}`);
        }
    }
  }
});
