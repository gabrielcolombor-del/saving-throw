const fs = require('fs');
const path = require('path');

const dir = path.join(__dirname, 'frontend', 'src', 'pages');
const files = ['Sons.tsx', 'Produto.tsx'];

files.forEach(file => {
  let content = fs.readFileSync(path.join(dir, file), 'utf8');

  if (content.includes('const _st_listeners = []')) {
      console.log('Already patched', file);
      return;
  }

  const wrapperStart = `
        const _st_listeners: any[] = [];
        const _st_origWinAdd = window.addEventListener;
        const _st_origDocAdd = document.addEventListener;
        
        window.addEventListener = function(t, l, o) {
            _st_listeners.push({ target: window, t, l, o });
            _st_origWinAdd.call(window, t, l, o);
        };
        document.addEventListener = function(t, l, o) {
            _st_listeners.push({ target: document, t, l, o });
            _st_origDocAdd.call(document, t, l, o);
        };
  `;

  const wrapperEnd = `
        window.addEventListener = _st_origWinAdd;
        document.addEventListener = _st_origDocAdd;
        return () => {
            _st_listeners.forEach(item => {
                item.target.removeEventListener(item.t, item.l, item.o);
            });
        };
  `;

  content = content.replace(/useEffect\(\(\) => \{/, 'useEffect(() => {' + wrapperStart);
  content = content.replace(/\/\/ Bindings generated by script/, wrapperEnd + '\n        // Bindings generated by script');

  fs.writeFileSync(path.join(dir, file), content);
  console.log('Fixed listeners in', file);
});
